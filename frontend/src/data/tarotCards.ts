export function getCardById(id: number): TarotCard | undefined {
  return TAROT_CARDS.find((card) => card.id === id);
}

export function getCardBySlug(slug: string): TarotCard | undefined {
  return TAROT_CARDS.find((card) => card.slug === slug);
}

export function getCardsBySuit(suit: "ALL" | "MAJOR" | "WANDS" | "CUPS" | "SWORDS" | "PENTACLES"): TarotCard[] {
  if (suit === "ALL") return TAROT_CARDS;
  return TAROT_CARDS.filter((card) => card.suit === suit);
}
